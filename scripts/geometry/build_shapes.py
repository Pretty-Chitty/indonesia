#!/usr/bin/env python3
"""Trace the goods glyphs (art/build/icon_<good>.png, cut from the player aid by scripts/art/extract_tts.py) into
outlines for the wooden goods markers (C9): the DLC's wooden markers are these silhouettes extruded. Writes
src/geometry/shapes.ts: one polygon per good in a unit box (x, y in 0..1 of the glyph's bounding box, y up) with the
glyph's aspect ratio. Run after extract_tts.py.
"""
import sys, site, os, json
sys.path.append(site.getusersitepackages())
import cv2, numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BUILD = os.path.join(ROOT, 'art', 'build')
GOODS = ['rice', 'spice', 'rubber', 'siapsaji', 'oil', 'ship']
out = {}
for g in GOODS:
    im = cv2.imread(os.path.join(BUILD, f'icon_{g}.png'), cv2.IMREAD_UNCHANGED)
    if im is None or im.shape[2] != 4: raise SystemExit(f'no RGBA icon for {g}')
    a = (im[:, :, 3] > 128).astype(np.uint8)
    a = cv2.morphologyEx(a, cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8))
    cs, _ = cv2.findContours(a, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    c = max(cs, key=cv2.contourArea)
    x, y, w, h = cv2.boundingRect(c)
    poly = cv2.approxPolyDP(c, 0.008 * max(w, h), True)[:, 0, :]
    pts = [[round((px - x) / w, 4), round(1 - (py - y) / h, 4)] for px, py in poly]
    out[g] = dict(aspect=round(w / h, 4), points=pts)
    print(g, 'bbox', (w, h), 'points', len(pts))
lines = ['// Generated by scripts/geometry/build_shapes.py from the player-aid glyphs. Do not edit.',
         'export const GLYPH_SHAPES: Record<string, { aspect: number; points: [number, number][] }> = ' + json.dumps(out) + ';']
os.makedirs(os.path.join(ROOT, 'src', 'geometry'), exist_ok=True)
open(os.path.join(ROOT, 'src', 'geometry', 'shapes.ts'), 'w').write('\n'.join(lines) + '\n')
print('wrote src/geometry/shapes.ts')
