#!/usr/bin/env python3
"""The wooden goods markers (C9) as the rulebook draws them: rules.pdf page 2 shows the five pieces in a row (oil,
rubber, siap saji, rice, spice), each a coloured silhouette screen-printed with its good. For each piece this writes
  - art/build/piece_<good>.png: the printed face, cropped to the silhouette's bounding box, opaque (the paper
    around the silhouette is filled with the piece's own colour, so no dark fringe shows at the cut), 2x;
  - src/geometry/goodsPieces.ts: the silhouette as a polygon in a unit box (x, y in 0..1 of the bounding box,
    y up), its aspect ratio, and the piece's wood and ink colours;
and ships the faces into src/assets/pieces (the packer resizes them).
"""
import sys, site, os, io, json
sys.path.append(site.getusersitepackages())
import cv2, numpy as np
from PIL import Image
from pypdf import PdfReader

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BUILD = os.path.join(ROOT, 'art', 'build')
ORDER = ['oil', 'rubber', 'siapsaji', 'rice', 'spice']   # left to right on the page


def expect(what, got, want):
    if got != want: raise SystemExit(f'{what}: expected {want}, got {got}')


# the goods row is the only 809 x 212 image on page 2
row = [im.image for im in PdfReader(os.path.join(ROOT, 'rules.pdf')).pages[1].images if im.image.size == (809, 212)]
expect('goods rows on page 2', len(row), 1)
rgba = np.array(row[0].convert('RGBA'))
alpha = rgba[:, :, 3]

# one piece per run of columns holding opaque pixels
cols = (alpha > 128).any(0)
runs, start = [], None
for x, c in enumerate(list(cols) + [False]):
    if c and start is None: start = x
    if not c and start is not None: runs.append((start, x)); start = None
expect('pieces in the goods row', len(runs), 5)

shapes = {}
for good, (x0, x1) in zip(ORDER, runs):
    a = (alpha[:, x0:x1] > 128).astype(np.uint8)
    a = cv2.morphologyEx(a, cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8))
    cs, _ = cv2.findContours(a, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    c = max(cs, key=cv2.contourArea)
    x, y, w, h = cv2.boundingRect(c)
    poly = cv2.approxPolyDP(c, 0.006 * max(w, h), True)[:, 0, :]
    points = [[round((px - x) / w, 4), round(1 - (py - y) / h, 4)] for px, py in poly]

    piece = rgba[y:y + h, x0 + x:x0 + x + w].astype(float)
    inside = piece[:, :, 3] > 250
    rgb = piece[:, :, :3]
    # the wood: the commonest colour in the band just inside the edge (the print covers most of the oil and rice
    # pieces, so the commonest colour overall is their ink); the ink: the commonest colour far from the wood
    band = inside & ~cv2.erode(inside.astype(np.uint8), np.ones((9, 9), np.uint8)).astype(bool)
    q = (rgb[band] // 8).astype(int)
    keys, counts = np.unique(q[:, 0] * 1024 + q[:, 1] * 32 + q[:, 2], return_counts=True)
    k = keys[counts.argmax()]
    wood = rgb[band][(q[:, 0] * 1024 + q[:, 1] * 32 + q[:, 2]) == k].mean(0)
    far = rgb[inside][np.linalg.norm(rgb[inside] - wood, axis=1) > 90]
    if len(far) < 50: raise SystemExit(f'{good}: no print found')
    qf = (far // 8).astype(int)
    keys, counts = np.unique(qf[:, 0] * 1024 + qf[:, 1] * 32 + qf[:, 2], return_counts=True)
    ink = far[(qf[:, 0] * 1024 + qf[:, 1] * 32 + qf[:, 2]) == keys[counts.argmax()]].mean(0)

    # opaque face: the print over the wood colour (the cut follows the polygon, so the corners never show)
    op = piece[:, :, 3:4] / 255
    face = rgb * op + wood * (1 - op)
    face_img = Image.fromarray(np.clip(face, 0, 255).astype(np.uint8)).resize((w * 2, h * 2), Image.LANCZOS)
    face_img.save(os.path.join(BUILD, f'piece_{good}.png'))

    hexc = lambda v: '#%02x%02x%02x' % tuple(int(round(t)) for t in v)
    shapes[good] = dict(aspect=round(w / h, 4), wood=hexc(wood), ink=hexc(ink), points=points)
    print(good, 'bbox', (w, h), 'points', len(points), 'wood', hexc(wood), 'ink', hexc(ink))

lines = ['// Generated by scripts/art/rulebook_goods.py from the goods pieces on rules.pdf page 2. Do not edit.',
         '/** Each wooden goods marker as the rulebook draws it: its silhouette (x, y in 0..1 of its bounding box, y up),',
         ' *  aspect ratio, wood colour, and the colour of the good printed on it. */',
         'export const GOODS_PIECES: Record<"oil" | "rubber" | "siapsaji" | "rice" | "spice", { aspect: number; wood: string; ink: string; points: [number, number][] }> = ' + json.dumps(shapes) + ';']
open(os.path.join(ROOT, 'src', 'geometry', 'goodsPieces.ts'), 'w').write('\n'.join(lines) + '\n')
print('wrote src/geometry/goodsPieces.ts')

# ship the faces
d = os.path.join(ROOT, 'src', 'assets', 'pieces'); os.makedirs(d, exist_ok=True)
for f in os.listdir(d):
    if f != 'sprite.json': os.remove(os.path.join(d, f))
for good in ORDER:
    open(os.path.join(d, f'{good}.png'), 'wb').write(open(os.path.join(BUILD, f'piece_{good}.png'), 'rb').read())
json.dump({"default": {"maxWidth": 320, "format": "png", "palette": True}}, open(os.path.join(d, 'sprite.json'), 'w'), indent=2)
print('shipped', len(ORDER), 'faces into src/assets/pieces')
